-- 验证化学品数据
SELECT '===== 化学品数据 =====' AS 章节;
SELECT 编号, CAS号, 中文名, 英文名, 分子式 FROM 化学品;

-- 验证同义词数量
SELECT '===== 同义词统计 =====' AS 章节;
SELECT c.中文名, COUNT(a.编号) AS 别名数量 
FROM 化学品 c 
LEFT JOIN 化学品别名 a ON c.编号 = a.化学品编号 
GROUP BY c.编号, c.中文名;

-- 验证MSDS章节数量
SELECT '===== MSDS章节统计 =====' AS 章节;
SELECT c.中文名, COUNT(s.编号) AS 章节数量 
FROM 化学品 c 
JOIN MSDS文档 m ON c.编号 = m.化学品编号 
JOIN MSDS章节 s ON m.编号 = s.文档编号 
GROUP BY c.编号, c.中文名;

