SELECT '法规条款数据插入完成！' AS 消息;

-- 验证法规文档
SELECT '===== 法规文档 =====' AS 章节;
SELECT 编号, 文档类型, 标题, 生效日期, 状态 FROM 法规文档;

-- 验证条款数量
SELECT '===== 条款统计 =====' AS 章节;
SELECT d.标题, COUNT(c.编号) AS 条款数量
FROM 法规文档 d
JOIN 文档版本 v ON d.编号 = v.文档编号
JOIN 法规条款 c ON v.编号 = c.版本编号
GROUP BY d.编号, d.标题;

-- 验证化学品-条款映射
SELECT '===== 化学品-条款映射 =====' AS 章节;
SELECT 
    h.中文名 AS 化学品,
    COUNT(m.编号) AS 关联条款数,
    ROUND(AVG(m.相关度评分), 2) AS 平均相关度
FROM 化学品 h
LEFT JOIN 化学品条款映射 m ON h.编号 = m.化学品编号
GROUP BY h.编号, h.中文名;

-- 验证操作规程数量
SELECT '===== 操作规程统计 =====' AS 章节;
SELECT 
    h.中文名 AS 化学品,
    COUNT(s.编号) AS 规程数量
FROM 化学品 h
LEFT JOIN 操作规程库 s ON h.编号 = s.化学品编号
GROUP BY h.编号, h.中文名;

-- 验证应急卡片
SELECT '===== 应急卡片统计 =====' AS 章节;
SELECT 
    h.中文名 AS 化学品,
    COUNT(e.编号) AS 应急卡数量
FROM 化学品 h
LEFT JOIN 应急卡片 e ON h.编号 = e.化学品编号
GROUP BY h.编号, h.中文名;

