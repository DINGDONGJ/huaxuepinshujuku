USE 危化品数据库;

-- ============================================================================
-- 查询 1：通过名称/别名/CAS号检索化学品
-- ============================================================================

SELECT '===== 查询 1：化学品检索 =====' AS 查询章节;

-- 示例1：通过中文名检索
SELECT 
    c.编号,
    c.CAS号,
    c.中文名,
    c.英文名,
    c.分子式
FROM 化学品 c
LEFT JOIN 化学品别名 a ON c.编号 = a.化学品编号
WHERE c.中文名 LIKE '%甲醛%'
   OR c.英文名 LIKE '%甲醛%'
   OR a.名称 LIKE '%甲醛%'
   OR c.CAS号 = '甲醛'
GROUP BY c.编号
LIMIT 10;

-- 示例2：通过CAS号精确检索
SELECT 
    c.编号,
    c.CAS号,
    c.中文名,
    c.英文名,
    c.分子式
FROM 化学品 c
WHERE c.CAS号 = '50-00-0';

-- 示例3：全文检索（使用FULLTEXT索引）
SELECT 
    c.编号,
    c.CAS号,
    c.中文名,
    c.英文名,
    MATCH(a.名称) AGAINST('乙醇 酒精' IN NATURAL LANGUAGE MODE) AS 相关度
FROM 化学品 c
JOIN 化学品别名 a ON c.编号 = a.化学品编号
WHERE MATCH(a.名称) AGAINST('乙醇 酒精' IN NATURAL LANGUAGE MODE)
ORDER BY 相关度 DESC;

-- ============================================================================
-- 查询 2：获取管理要求（法规条款）
-- ============================================================================

SELECT '===== 查询 2：管理要求（法规条款） =====' AS 查询章节;

-- 获取甲醛的管理要求
SET @目标化学品编号 = (SELECT 编号 FROM 化学品 WHERE CAS号 = '50-00-0' LIMIT 1);

SELECT 
    d.文档类型,
    d.标题 AS 法规名称,
    v.版本标签,
    c.条款编号,
    c.标题 AS 条款标题,
    SUBSTRING(c.内容, 1, 200) AS 条款摘要,
    c.分类,
    m.相关度评分,
    m.标签,
    c.链接 AS PDF链接,
    d.官方链接
FROM 化学品条款映射 m
JOIN 法规条款 c ON c.编号 = m.条款编号
JOIN 文档版本 v ON v.编号 = c.版本编号 AND v.是否当前版本 = 1
JOIN 法规文档 d ON d.编号 = v.文档编号
WHERE m.化学品编号 = @目标化学品编号
  AND c.分类 = '管理要求'
  AND d.状态 = '有效'
ORDER BY m.相关度评分 DESC, d.生效日期 DESC
LIMIT 20;

-- 获取所有分类的条款
SELECT 
    c.分类 AS 条款类型,
    d.文档类型,
    d.标题 AS 法规名称,
    c.条款编号,
    c.标题 AS 条款标题,
    m.相关度评分,
    m.标签
FROM 化学品条款映射 m
JOIN 法规条款 c ON c.编号 = m.条款编号
JOIN 文档版本 v ON v.编号 = c.版本编号 AND v.是否当前版本 = 1
JOIN 法规文档 d ON d.编号 = v.文档编号
WHERE m.化学品编号 = @目标化学品编号
  AND d.状态 = '有效'
ORDER BY c.分类, m.相关度评分 DESC;

-- ============================================================================
-- 查询 3：获取使用要求（操作规程 + MSDS第8部分）
-- ============================================================================

SELECT '===== 查询 3：使用要求 =====' AS 查询章节;

-- 操作规程
SELECT '--- 操作规程 ---' AS 小节;

SELECT 
    s.标题 AS 规程标题,
    s.适用范围,
    s.版本标签,
    s.正文 AS 规程内容
FROM 操作规程库 s
WHERE (s.化学品编号 = @目标化学品编号 OR s.化学品编号 IS NULL)
  AND s.适用范围 IN ('操作', '储存', '防护', '处置')
ORDER BY 
    CASE WHEN s.化学品编号 IS NULL THEN 1 ELSE 0 END,
    s.适用范围;

-- 操作规程步骤
SELECT '--- 操作规程步骤 ---' AS 小节;

SELECT 
    s.标题 AS 规程名称,
    t.步骤序号,
    t.步骤内容
FROM 操作规程库 s
JOIN 操作规程步骤 t ON s.编号 = t.规程编号
WHERE s.化学品编号 = @目标化学品编号
ORDER BY s.编号, t.步骤序号;

-- MSDS第8部分：个体防护
SELECT '--- MSDS第8部分：个体防护 ---' AS 小节;

SELECT 
    s.章节标题,
    s.内容 AS 防护要求,
    s.结构化数据
FROM MSDS章节 s
JOIN MSDS文档 m ON m.编号 = s.文档编号
WHERE m.化学品编号 = @目标化学品编号
  AND s.章节序号 = 8;

-- ============================================================================
-- 查询 4：获取识别与许可信息
-- ============================================================================

SELECT '===== 查询 4：识别与许可 =====' AS 查询章节;

-- 运输分类信息
SELECT '--- 运输分类 ---' AS 小节;

SELECT 
    t.UN编号,
    t.UN运输名称,
    t.主要危险类别,
    t.次要危险类别,
    t.包装类别,
    CASE WHEN t.是否海洋污染物 = 1 THEN '是' ELSE '否' END AS 海洋污染物,
    t.运输注意事项
FROM 运输分类 t
WHERE t.化学品编号 = @目标化学品编号;

-- GHS分类信息
SELECT '--- GHS危害分类 ---' AS 小节;

SELECT 
    g.危害类别,
    g.类别编号,
    g.信号词,
    g.象形图,
    g.H代码,
    g.P代码,
    g.数据来源
FROM GHS分类 g
WHERE g.化学品编号 = @目标化学品编号;

-- 危险品目录标识
SELECT '--- 危险品目录标识 ---' AS 小节;

SELECT 
    f.目录名称,
    CASE WHEN f.是否列入 = 1 THEN '已列入' ELSE '未列入' END AS 列入状态,
    f.参考文号
FROM 危险品目录标识 f
WHERE f.化学品编号 = @目标化学品编号
ORDER BY f.是否列入 DESC, f.目录名称;

-- 综合识别卡片
SELECT '--- 综合识别卡 ---' AS 小节;

SELECT 
    c.中文名 AS 化学品名称,
    c.CAS号,
    c.分子式,
    t.UN编号,
    t.主要危险类别,
    t.包装类别,
    GROUP_CONCAT(DISTINCT g.信号词) AS 信号词,
    GROUP_CONCAT(DISTINCT f.目录名称 SEPARATOR '; ') AS 列入目录
FROM 化学品 c
LEFT JOIN 运输分类 t ON c.编号 = t.化学品编号
LEFT JOIN GHS分类 g ON c.编号 = g.化学品编号
LEFT JOIN 危险品目录标识 f ON c.编号 = f.化学品编号 AND f.是否列入 = 1
WHERE c.编号 = @目标化学品编号
GROUP BY c.编号;

-- ============================================================================
-- 查询 5：获取应急措施
-- ============================================================================

SELECT '===== 查询 5：应急措施 =====' AS 查询章节;

-- MSDS第4/5/6部分
SELECT '--- MSDS应急章节 ---' AS 小节;

SELECT 
    s.章节序号,
    s.章节标题,
    s.内容 AS 应急措施内容
FROM MSDS章节 s
JOIN MSDS文档 m ON m.编号 = s.文档编号
WHERE m.化学品编号 = @目标化学品编号
  AND s.章节序号 IN (4, 5, 6)
ORDER BY s.章节序号;

-- 应急卡片
SELECT '--- 应急卡片 ---' AS 小节;

SELECT 
    e.类型,
    CASE 
        WHEN e.类型 = '急救措施' THEN '急救措施'
        WHEN e.类型 = '消防措施' THEN '消防措施'
        WHEN e.类型 = '泄漏处置' THEN '泄漏处置'
    END AS 类型说明,
    e.内容 AS 应急内容,
    e.版本标签
FROM 应急卡片 e
WHERE e.化学品编号 = @目标化学品编号
   OR e.化学品编号 IS NULL
ORDER BY 
    CASE WHEN e.化学品编号 IS NULL THEN 1 ELSE 0 END,
    e.类型;

-- ============================================================================
-- 查询 6：完整的四块卡片组装（JSON输出）
-- ============================================================================

SELECT '===== 查询 6：四块卡片完整输出 =====' AS 查询章节;

-- 化学品基本信息
SELECT 
    JSON_OBJECT(
        '化学品', JSON_OBJECT(
            '编号', c.编号,
            '名称', c.中文名,
            'CAS号', c.CAS号,
            '分子式', c.分子式,
            '英文名', c.英文名
        )
    ) AS 化学品信息
FROM 化学品 c
WHERE c.编号 = @目标化学品编号;

-- 管理要求（JSON数组）
SELECT 
    JSON_ARRAYAGG(
        JSON_OBJECT(
            '文档类型', d.文档类型,
            '标题', d.标题,
            '条款编号', c.条款编号,
            '条款标题', c.标题,
            '摘要', SUBSTRING(c.内容, 1, 200),
            '相关度评分', m.相关度评分,
            '标签', m.标签,
            '链接', c.链接
        )
    ) AS 管理要求
FROM 化学品条款映射 m
JOIN 法规条款 c ON c.编号 = m.条款编号
JOIN 文档版本 v ON v.编号 = c.版本编号 AND v.是否当前版本 = 1
JOIN 法规文档 d ON d.编号 = v.文档编号
WHERE m.化学品编号 = @目标化学品编号
  AND c.分类 = '管理要求';

-- 识别与许可（JSON对象）
SELECT 
    JSON_OBJECT(
        '运输信息', (
            SELECT JSON_OBJECT(
                'UN编号', UN编号,
                '危险类别', 主要危险类别,
                '包装类别', 包装类别,
                '海洋污染物', 是否海洋污染物
            )
            FROM 运输分类
            WHERE 化学品编号 = @目标化学品编号
            LIMIT 1
        ),
        '目录标识', (
            SELECT JSON_ARRAYAGG(
                JSON_OBJECT(
                    '目录', 目录名称,
                    '是否列入', 是否列入,
                    '参考文号', 参考文号
                )
            )
            FROM 危险品目录标识
            WHERE 化学品编号 = @目标化学品编号
        ),
        'GHS分类', (
            SELECT JSON_ARRAYAGG(
                JSON_OBJECT(
                    '危害类别', 危害类别,
                    '类别编号', 类别编号,
                    '信号词', 信号词,
                    'H代码', H代码,
                    'P代码', P代码
                )
            )
            FROM GHS分类
            WHERE 化学品编号 = @目标化学品编号
        )
    ) AS 识别与许可;

-- ============================================================================
-- 查询 7：理化特性
-- ============================================================================

SELECT '===== 查询 7：理化特性 =====' AS 查询章节;

SELECT 
    p.外观,
    p.pH值,
    p.熔点,
    p.沸点,
    p.闪点,
    p.爆炸极限,
    p.蒸气压,
    p.相对密度,
    p.溶解性,
    p.自燃温度
FROM MSDS理化特性 p
JOIN MSDS文档 m ON m.编号 = p.文档编号
WHERE m.化学品编号 = @目标化学品编号;

-- ============================================================================
-- 查询 8：数据统计
-- ============================================================================

SELECT '===== 查询 8：数据统计 =====' AS 查询章节;

-- 数据库整体统计
SELECT 
    '数据库整体统计' AS 统计类型,
    (SELECT COUNT(*) FROM 化学品) AS 化学品总数,
    (SELECT COUNT(*) FROM 法规文档 WHERE 状态 = '有效') AS 有效法规文档数,
    (SELECT COUNT(*) FROM 法规条款) AS 法规条款总数,
    (SELECT COUNT(*) FROM 化学品条款映射) AS 映射关系总数,
    (SELECT COUNT(*) FROM 操作规程库) AS 操作规程总数,
    (SELECT COUNT(*) FROM 应急卡片) AS 应急卡总数;

-- 各化学品数据完整性统计
SELECT 
    c.中文名 AS 化学品,
    COUNT(DISTINCT a.编号) AS 别名数,
    COUNT(DISTINCT g.编号) AS GHS分类数,
    COUNT(DISTINCT s.编号) AS MSDS章节数,
    COUNT(DISTINCT m.编号) AS 关联条款数,
    COUNT(DISTINCT op.编号) AS 操作规程数,
    COUNT(DISTINCT e.编号) AS 应急卡数
FROM 化学品 c
LEFT JOIN 化学品别名 a ON c.编号 = a.化学品编号
LEFT JOIN GHS分类 g ON c.编号 = g.化学品编号
LEFT JOIN MSDS文档 md ON c.编号 = md.化学品编号
LEFT JOIN MSDS章节 s ON md.编号 = s.文档编号
LEFT JOIN 化学品条款映射 m ON c.编号 = m.化学品编号
LEFT JOIN 操作规程库 op ON c.编号 = op.化学品编号
LEFT JOIN 应急卡片 e ON c.编号 = e.化学品编号
GROUP BY c.编号, c.中文名;

